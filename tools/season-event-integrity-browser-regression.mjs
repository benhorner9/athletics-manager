   keep.completed=true;keep.decision=true;keep.qaSentinel='preserve-me';keep.results={QA:[{id:'qa',place:1}]};
   const fakeRoad={id:'road-spring',name:'Retired Marathon QA',week:10,roadRace:true,disc:['MMarathon','WMarathon'],decision:false,completed:false,entries:{},results:{}};
