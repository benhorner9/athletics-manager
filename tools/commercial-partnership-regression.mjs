import fs from 'node:fs';
import assert from 'node:assert/strict';
const js=fs.readFileSync('scripts/commercial-partnership-v1.js','utf8');
const html=fs.readFileSync('game.html','utf8');
const calendar=fs.readFileSync('scripts/calendar-v2.js','utf8');
assert.match(html,/styles\/commercial-partnership-v1\.css/,'commercial partnership stylesheet must load');
assert.match(html,/scripts\/commercial-partnership-v1\.js/,'commercial partnership runtime must load');
assert.match(js,/function signSponsor\(id\).*renderMeeting\(id\)/s,'sponsor action must open a meeting instead of paying instantly');
assert.match(js,/stage:'opening'/,'sponsor negotiations must persist a conversation stage');
assert.match(js,/m\.stage='terms'/,'sponsor meeting must include negotiation before final terms');
assert.match(js,/m\.stage='final'/,'sponsor meeting must reach a final offer before signing');
assert.match(js,/signingPayment=roundMoney\(annual\*\.25\)/,'only a staged signing payment should be paid immediately');
assert.match(js,/midPayment=roundMoney\(annual\*\.35\)/,'partnership must include an in-season payment');
assert.match(js,/finalPayment=Math\.max\(0,annual-signingPayment-midPayment\)/,'partnership must retain a season-review payment');
assert.match(js,/requiredMedia:m\.requiredMedia/,'signed contracts must persist media obligations');
assert.match(js,/scheduleMediaEvents\(deal,offer\)/,'signing must place media commitments into the season');
for(const type of ['press','charity','grassroots','campaign','gala'])assert.match(js,new RegExp(`${type}:\\{title:`),`commercial calendar must support ${type} events`);
assert.match(js,/status:'scheduled'/,'new commercial appearances must begin as scheduled commitments');
assert.match(js,/completeMedia\(ev,'attended'/,'attending must fulfil a media commitment');
assert.match(js,/completeMedia\(ev,'delegated'/,'delegation must be tracked separately from personal attendance');
assert.match(js,/completeMedia\(ev,'declined'/,'declining must create a sponsor consequence');
assert.match(js,/completeMedia\(ev,'missed'/,'advancing past an unresolved appearance must mark it missed');
assert.match(js,/bonusMet=mediaMet&&perf/,'performance bonus must also require commercial commitments');
assert.match(js,/relationship\(deal\.id\)/,'season review must retain sponsor relationship state');
assert.match(js,/loyalty=clamp\(\(rel-55\)\/500/,'future offers must respond to sponsor relationship history');
assert.match(js,/data-commercial-media-open/,'calendar/email actions must open media events');
assert.match(calendar,/AMCommercialPartnership\?\.eventsForWeek/,'Calendar V2 must include commercial events');
assert.match(calendar,/mediaEvents\(w\)\.length/,'Calendar programme filter must include commercial appearances');
assert.match(calendar,/itemHTML\('media'/,'Calendar timeline must show media appearances');
assert.match(calendar,/calendarDetailHTML/,'Calendar V2 must render media event details');
console.log('Commercial partnership regression passed.');
